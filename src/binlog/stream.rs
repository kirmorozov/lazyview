/// missing-binlog policy this is the same answer as 1236 "purged": the requested position is
/// gone. (1236 itself is classified by [`missing_binlog_message`], which owns its wording.)
const ER_MISSING_GTID: u16 = 3082;

/// The first writable offset of a binlog file (after its format-description event). A GTID dump
/// reads no position, but the dump thread still refuses anything below this.
const BINLOG_START_POS: u64 = 4;

/// No file name at all: what a GTID start sends, so the request says nothing about this server's
/// files. On MariaDB it is also how the dump thread is told to read the start from
